async function pathExists(p: string): Promise<boolean> {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function confirmOverwrite(io: CliIO, yes: boolean): Promise<boolean> {
  if (yes) return true;
  // Try interactive confirmation when available; otherwise require --yes.
  const stdin: any = (globalThis as any).process?.stdin;
  const stdout: any = (globalThis as any).process?.stdout;
  if (stdin?.isTTY && stdout?.isTTY && typeof stdin.once === "function") {
    io.stderr("Target directory is not empty. Overwrite demo contents? [y/N] ");
    const answer = await new Promise<string>((resolve) => {
      let data = "";
      const onData = (chunk: Buffer | string) => {
        data += String(chunk);
        if (data.includes("\n")) cleanup();
      };
      const onEnd = () => cleanup();
      const cleanup = () => {
        try { stdin.off?.("data", onData); } catch {}
        try { stdin.off?.("end", onEnd); } catch {}
        resolve(data.trim());
      };
      stdin.on("data", onData);
      stdin.once("end", onEnd);
      try { stdin.resume?.(); } catch {}
    });
    return /^y(es)?$/i.test(answer);
  }
  return false;
}

function assertInsideTarget(targetDir: string, relPath: string): string {
  const absTarget = path.resolve(targetDir);
  const absPath = path.resolve(absTarget, relPath);
  const prefix = absTarget.endsWith(path.sep) ? absTarget : absTarget + path.sep;
  if (absPath !== absTarget && !absPath.startsWith(prefix)) {
    throw new HarnessError("Demo generator refused to write outside target directory", {
      code: "harness_error",
      details: { targetDir: absTarget, relPath },
    });
  }
  return absPath;
}

export async function generateDemoProject(options: DemoOptions, io: CliIO): Promise<DemoResult> {
  const targetDir = path.resolve(options.targetDir);
  const exists = await pathExists(targetDir);
  const entries = exists ? await fs.readdir(targetDir) : [];
  const isEmpty = entries.length === 0;
  const markerPath = path.join(targetDir, DEMO_MARKER);
  const hasDemoMarker = exists && await pathExists(markerPath);

  if (exists && !isEmpty) {
    if (hasDemoMarker) {
      // Idempotent regeneration for existing demo-marker directories (documented policy):
      // regenerate deterministically for the same target/seed without requiring --force.
      // Never mutate user files outside the demo target contents we own.
    } else {
      if (!options.force) {
        throw new CliUsageError(
          "Refusing to generate demo into a non-empty directory without --force (use --force --yes to overwrite demo target after confirmation).",
          { targetDir },
        );
      }
      const confirmed = await confirmOverwrite(io, options.yes);
      if (!confirmed) {
        throw new CliUsageError(
          "Overwrite not confirmed. Re-run with --force --yes to overwrite a non-empty target directory.",
          { targetDir },
        );
      }
    }
  }

  await fs.mkdir(targetDir, { recursive: true });

  const files = demoFiles(options.seed).sort((a, b) => a.relPath.localeCompare(b.relPath));
  const written: string[] = [];
  for (const f of files) {
    const abs = assertInsideTarget(targetDir, f.relPath);
    await fs.mkdir(path.dirname(abs), { recursive: true });
    await fs.writeFile(abs, f.content, "utf8");
    written.push(f.relPath);
  }

  const marker = JSON.parse(files.find((f) => f.relPath === DEMO_MARKER)?.content ?? "{}") as Record<string, unknown>;
  return {
    targetDir,
    created: !exists || isEmpty,
    regenerated: hasDemoMarker,
    files: written,
    marker,
  };
}

export const demoCommand: CliCommandHandler = async (argv, io) => {
  // Local parse to support --yes and default target
  const flags: Record<string, string | boolean | string[]> = {};
  const positionals: string[] = [];
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i] ?? "";
    if (!arg.startsWith("--")) {
      positionals.push(arg);
      continue;
    }
    if (arg === "--force") { flags.force = true; continue; }
    if (arg === "--yes" || arg === "-y") { flags.yes = true; continue; }
    const eq = arg.indexOf("=");
    if (eq !== -1) {
      flags[arg.slice(2, eq)] = arg.slice(eq + 1);
      continue;
    }
    const key = arg.slice(2);
    const next = argv[i + 1];
    if (next !== undefined && !next.startsWith("--")) {
      flags[key] = next;
      i += 1;
    } else {
      flags[key] = true;
    }
  }

  const targetRaw = (typeof flags.target === "string" ? flags.target : positionals[0]) ?? "./lemma-demo";
  const seedRaw = typeof flags.seed === "string" ? flags.seed : undefined;
  const result = await generateDemoProject(
    {
      targetDir: targetRaw,
      force: flags.force === true,
      yes: flags.yes === true,
      seed: asInt(seedRaw, 1),
    },
    io,
  );

  return {
    exitCode: EXIT_CODES.pass,
    stdoutJson: {
      schema_version: "quality-harness.report/v1",
      command: "demo",
      status: "ok",
      test_only: true,
      warning: "Generated demo is test-only. Do not deploy.",
      ...result,
    },
  };
};
