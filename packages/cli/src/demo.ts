import path from "node:path";

import { EXIT_CODES, HarnessError } from "@lemma/core";

import { CliUsageError, type CliCommandHandler, type CliIO } from "./index-types.js";

export interface DemoOptions {
  targetDir: string;
  force: boolean;
  yes: boolean;
  seed: number;
}

export interface DemoResult {
  targetDir: string;
  created: boolean;
  regenerated: boolean;
  files: string[];
  marker: Record<string, unknown>;
}

const DEMO_MARKER = ".lemma-demo";
const DEPLOY_BLOCKER = "NOT-FOR-DEPLOYMENT";

function asInt(value: string | undefined, fallback: number): number {
  if (value === undefined) return fallback;
  const n = Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.trunc(n);
}

